using System;
using UnityEngine;

namespace Pickleball.Sandbox.Cloth
{
    /// <summary>
    /// Verlet spring chains for coat tails, cloaks and other hanging cloth.
    ///
    /// Why not Unity's Cloth component: both characters are single fused Tripo
    /// meshes (body + coat in one SkinnedMeshRenderer), so Cloth would have to
    /// own every vertex of the body, forces CPU skinning, needs Read/Write on
    /// the import, and Newton's skirt is ~100 vertices of big flat quads that
    /// PhysX cloth makes look like jelly. A handful of bone chains is a few
    /// dozen transforms of maths per frame, keeps GPU skinning, and is the
    /// standard mobile answer.
    ///
    /// The chains (child transforms of the Hips named ClothJoint_c_j) and the
    /// re-skinned mesh are generated by Tools ▸ Pickleball ▸ Setup Cloth; this
    /// component only simulates them. Each chain is pinned at its root (which
    /// rides the hips) and every joint below it is a particle that swings under
    /// gravity and inertia, springs back toward the animated pose, and is pushed
    /// out of capsules around the thighs and shins so the hem stops cutting
    /// through the legs on a run.
    ///
    /// Runs in LateUpdate because it has to read the pose the Animator just
    /// wrote and finish before rendering; there is no existing per-frame hook
    /// on the character that runs after animation.
    /// </summary>
    [DisallowMultipleComponent]
    public class SpringCloth : MonoBehaviour
    {
        [Serializable]
        public struct BoneCapsule
        {
            public Transform start;
            public Transform end;
            [Tooltip("Radius as a fraction of character height.")]
            public float radius;
        }

        [SerializeField] private SpringClothConfig config;

        [Tooltip("First joint of each chain. Each joint's first child is the next joint.")]
        [SerializeField] private Transform[] chainRoots = Array.Empty<Transform>();

        [SerializeField] private BoneCapsule[] colliders = Array.Empty<BoneCapsule>();

        [Tooltip("Character height in THIS transform's local units, measured at setup.")]
        [SerializeField] private float characterHeight = 1f;

        [Tooltip("Used to skip simulation while off-screen.")]
        [SerializeField] private Renderer visibilityRenderer;

        // Bookkeeping for the editor generator so it can undo itself cleanly.
        [SerializeField, HideInInspector] private Mesh sourceMesh;
        [SerializeField, HideInInspector] private Bounds sourceBounds;

        public SpringClothConfig Config => config;
        public Mesh SourceMesh => sourceMesh;
        public Bounds SourceBounds => sourceBounds;

        sealed class Chain
        {
            public Transform[] joints;
            public Quaternion[] restLocal;
            public Vector3[] pos;
            public Vector3[] prev;
            public Vector3[] rest;
        }

        Chain[] _chains = Array.Empty<Chain>();
        Vector3 _lastRoot;
        float _lastDt = 1f / 60f;
        bool _reset = true;
        Vector3[] _capA, _capB;
        float[] _capR;
        int _capCount;

        void Awake() => Rebind();

        void OnEnable() => _reset = true;

        void OnDisable() => RestorePose();

        /// <summary>Snap the cloth to the animated pose next frame — call after
        /// teleporting or respawning the character.</summary>
        public void ResetSimulation() => _reset = true;

        /// <summary>Re-read the chain hierarchy and rest pose. Called on Awake;
        /// call again if the joints are regenerated while running.</summary>
        public void Rebind()
        {
            int n = chainRoots?.Length ?? 0;
            _chains = new Chain[n];
            for (int c = 0; c < n; c++)
            {
                var root = chainRoots[c];
                int count = 0;
                for (var t = root; t != null; t = t.childCount > 0 ? t.GetChild(0) : null) count++;

                var chain = new Chain
                {
                    joints = new Transform[count],
                    restLocal = new Quaternion[count],
                    pos = new Vector3[count],
                    prev = new Vector3[count],
                    rest = new Vector3[count],
                };
                int i = 0;
                for (var t = root; t != null; t = t.childCount > 0 ? t.GetChild(0) : null, i++)
                {
                    chain.joints[i] = t;
                    chain.restLocal[i] = t.localRotation;
                }
                _chains[c] = chain;
            }
            _reset = true;
        }

        void LateUpdate() => Simulate(Time.deltaTime);

        /// <summary>One simulation step. Public so editor tooling can step it
        /// without entering Play mode.</summary>
        public void Simulate(float dt)
        {
            if (config == null || _chains.Length == 0) return;
            if (dt <= 0f) return; // hit-stop / pause: hold the last pose

            bool visible = config.simulateWhenInvisible || visibilityRenderer == null || visibilityRenderer.isVisible;
            if (!visible)
            {
                RestorePose();
                _reset = true;
                return;
            }

            dt = Mathf.Min(dt, 1f / 20f);
            float height = characterHeight * Mathf.Abs(transform.lossyScale.y);
            Vector3 rootPos = transform.position;
            Vector3 delta = rootPos - _lastRoot;
            _lastRoot = rootPos;
            float teleport = config.teleportDistance * height;
            if (delta.sqrMagnitude > teleport * teleport) _reset = true;

            float frames = dt * 60f;
            float dtRatio = Mathf.Clamp(dt / _lastDt, 0.5f, 2f);
            _lastDt = dt;
            Vector3 gravityStep = config.gravity * (dt * dt);
            Vector3 carry = _reset ? Vector3.zero : delta * (1f - config.inertia);
            float particleR = config.particleRadius * height;
            float legScale = config.legRadiusScale * height;
            CacheCapsules(legScale, particleR);

            foreach (var ch in _chains)
            {
                int n = ch.joints.Length;
                if (n == 0 || ch.joints[0] == null) continue;

                // Animated pose: undo last frame's swing, then read where the
                // Animator-driven hips put every joint.
                for (int j = 0; j < n; j++) ch.joints[j].localRotation = ch.restLocal[j];
                for (int j = 0; j < n; j++) ch.rest[j] = ch.joints[j].position;

                if (_reset)
                {
                    for (int j = 0; j < n; j++) ch.pos[j] = ch.prev[j] = ch.rest[j];
                    continue;
                }

                ch.pos[0] = ch.prev[0] = ch.rest[0];
                for (int j = 1; j < n; j++)
                {
                    float k = n > 2 ? (j - 1f) / (n - 2f) : 1f;
                    float damping = Mathf.Lerp(config.dampingRoot, config.dampingTip, k);
                    float stiffness = Mathf.Lerp(config.stiffnessRoot, config.stiffnessTip, k);
                    float keep = Mathf.Pow(1f - damping, frames);
                    float pull = 1f - Mathf.Pow(1f - stiffness, frames);

                    Vector3 p = ch.pos[j] + carry;
                    Vector3 velocity = (p - (ch.prev[j] + carry)) * (keep * dtRatio);
                    ch.prev[j] = p;

                    p += velocity + gravityStep;
                    p += (ch.rest[j] - p) * pull;

                    // Keep the segment length, limit the swing off the animated direction and
                    // stay out of the legs. Two passes: a push-out can break the length and
                    // re-projecting the length can pull back into a capsule near the parent.
                    Vector3 parent = ch.pos[j - 1];
                    Vector3 restDir = ch.rest[j] - ch.rest[j - 1];
                    float length = restDir.magnitude;
                    if (length < 1e-6f) { ch.pos[j] = ch.rest[j]; continue; }
                    for (int pass = 0; pass < 2; pass++)
                    {
                        for (int c = 0; c < _capCount; c++)
                            PushOutOfCapsule(ref p, _capA[c], _capB[c], _capR[c]);

                        Vector3 dir = p - parent;
                        if (dir.sqrMagnitude < 1e-12f) dir = restDir;
                        var swing = Quaternion.FromToRotation(restDir, dir);
                        swing = Quaternion.RotateTowards(Quaternion.identity, swing, config.maxAngle);
                        p = parent + (swing * restDir).normalized * length;
                    }
                    ch.pos[j] = p;
                }

                // Turn each joint so its child lands on the simulated particle.
                for (int j = 0; j < n - 1; j++)
                {
                    Vector3 from = ch.joints[j + 1].position - ch.joints[j].position;
                    Vector3 to = ch.pos[j + 1] - ch.joints[j].position;
                    if (from.sqrMagnitude < 1e-12f || to.sqrMagnitude < 1e-12f) continue;
                    ch.joints[j].rotation = Quaternion.FromToRotation(from, to) * ch.joints[j].rotation;
                }
            }

            _reset = false;
        }

        void CacheCapsules(float legScale, float particleR)
        {
            int n = colliders.Length;
            if (_capA == null || _capA.Length != n)
            {
                _capA = new Vector3[n]; _capB = new Vector3[n]; _capR = new float[n];
            }
            _capCount = 0;
            for (int c = 0; c < n; c++)
            {
                var cap = colliders[c];
                if (cap.start == null || cap.end == null) continue;
                _capA[_capCount] = cap.start.position;
                _capB[_capCount] = cap.end.position;
                _capR[_capCount] = cap.radius * legScale + particleR;
                _capCount++;
            }
        }

        void RestorePose()
        {
            foreach (var ch in _chains)
                for (int j = 0; j < ch.joints.Length; j++)
                    if (ch.joints[j] != null) ch.joints[j].localRotation = ch.restLocal[j];
        }

        static void PushOutOfCapsule(ref Vector3 p, Vector3 a, Vector3 b, float radius)
        {
            Vector3 ab = b - a;
            float t = Mathf.Clamp01(Vector3.Dot(p - a, ab) / Mathf.Max(ab.sqrMagnitude, 1e-8f));
            Vector3 closest = a + ab * t;
            Vector3 d = p - closest;
            float sq = d.sqrMagnitude;
            if (sq >= radius * radius || sq < 1e-12f) return;
            p = closest + d * (radius / Mathf.Sqrt(sq));
        }

        void OnDrawGizmosSelected()
        {
            float height = characterHeight * Mathf.Abs(transform.lossyScale.y);
            Gizmos.color = new Color(1f, 0.6f, 0.1f, 0.9f);
            if (chainRoots != null)
                foreach (var root in chainRoots)
                    for (var t = root; t != null && t.childCount > 0; t = t.GetChild(0))
                        Gizmos.DrawLine(t.position, t.GetChild(0).position);

            if (colliders == null || config == null) return;
            Gizmos.color = new Color(0.2f, 0.8f, 1f, 0.6f);
            foreach (var cap in colliders)
            {
                if (cap.start == null || cap.end == null) continue;
                float r = cap.radius * config.legRadiusScale * height;
                Gizmos.DrawWireSphere(cap.start.position, r);
                Gizmos.DrawWireSphere(cap.end.position, r);
                Gizmos.DrawLine(cap.start.position, cap.end.position);
            }
        }
    }
}
