using System.Linq;
using Pickleball.Sandbox;
using Pickleball.Sandbox.Combat;
using Pickleball.Sandbox.Combat.Presentation;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;

/// <summary>
/// Tools ▸ Pickleball ▸ Setup Combat Voice. Idempotently:
///
///  1. Sets every clip under <c>Audio/Combat/Voice/</c> to play with no load delay.
///  2. Creates <c>ScriptableObjects/Combat/CombatVoiceBank.asset</c> and fills each empty
///     group from its folder. A group that already has clips is left alone, so clips a
///     person dragged out stay out. Empty a group to have it refilled.
///  3. Adds <see cref="CombatVoice"/> to the player, next to its MeleeCombat. This is a
///     scene override, like the inventory, not part of Chibi.prefab: Health is added per
///     scene, and the prefab is regenerated by Setup Chibi Sandbox.
///
/// <see cref="AttachToPlayer"/> is called by Setup Chibi Sandbox and Build Training Stage,
/// so those chains keep the voice. For any other scene, open it and run the menu.
/// </summary>
public static class CombatVoiceSetup
{
    const string VoiceDir = "Assets/_Project/Audio/Combat/Voice";
    const string BankPath = "Assets/_Project/ScriptableObjects/Combat/CombatVoiceBank.asset";
    const float VorbisQuality = 0.7f;

    static readonly (string field, string folder)[] Groups =
    {
        ("light", "Light"), ("medium", "Medium"), ("heavy", "Heavy"),
        ("finisher", "Finisher"), ("hurt", "Hurt"),
    };

    [MenuItem("Tools/Pickleball/Setup Combat Voice")]
    public static void Run()
    {
        if (EditorApplication.isPlayingOrWillChangePlaymode)
        {
            Debug.LogError("Setup Combat Voice edits assets and the scene — exit Play first.");
            return;
        }
        var player = Object.FindFirstObjectByType<ChibiLocomotion>();
        if (player == null)
        {
            Debug.LogError("Setup Combat Voice: no ChibiLocomotion in the open scene.");
            return;
        }
        AttachToPlayer(player.gameObject);
        AssetDatabase.SaveAssets();
    }

    /// <summary>Everything the menu does for one player. Marks the scene dirty if the
    /// wiring changed and saves nothing; the caller saves the scene.</summary>
    public static void AttachToPlayer(GameObject player)
    {
        if (EditorApplication.isPlayingOrWillChangePlaymode || player == null) return;
        ConfigureImports();
        var bank = CreateOrFillBank();

        var combat = player.GetComponent<MeleeCombat>();
        if (combat == null)
        {
            Debug.LogError($"[CombatVoiceSetup] {player.name} has no MeleeCombat, so it has nothing to voice.");
            return;
        }

        var voice = player.GetComponent<CombatVoice>();
        bool added = voice == null;
        if (added) voice = player.AddComponent<CombatVoice>();

        var so = new SerializedObject(voice);
        so.FindProperty("combat").objectReferenceValue = combat;
        so.FindProperty("bank").objectReferenceValue = bank;
        // Left empty where Health hasn't been added yet (Setup Newton Fight adds it);
        // CombatVoice finds it on the same object at runtime.
        so.FindProperty("health").objectReferenceValue = player.GetComponent<Health>();
        if ((so.ApplyModifiedPropertiesWithoutUndo() || added) && player.scene.IsValid())
            EditorSceneManager.MarkSceneDirty(player.scene);
    }

    static string[] ClipPaths(string folder)
        => AssetDatabase.FindAssets("t:AudioClip", new[] { folder })
                        .Select(AssetDatabase.GUIDToAssetPath)
                        .OrderBy(p => p, System.StringComparer.Ordinal)
                        .ToArray();

    /// <summary>Short clips, decompressed up front so a grunt starts on the frame it is asked for.</summary>
    static void ConfigureImports()
    {
        foreach (var path in ClipPaths(VoiceDir))
        {
            var importer = (AudioImporter)AssetImporter.GetAtPath(path);
            var settings = importer.defaultSampleSettings;
            bool same = importer.forceToMono
                        && settings.loadType == AudioClipLoadType.DecompressOnLoad
                        && settings.compressionFormat == AudioCompressionFormat.Vorbis
                        && Mathf.Approximately(settings.quality, VorbisQuality)
                        && settings.preloadAudioData;
            if (same) continue;

            importer.forceToMono = true;
            settings.loadType = AudioClipLoadType.DecompressOnLoad;
            settings.compressionFormat = AudioCompressionFormat.Vorbis;
            settings.quality = VorbisQuality;
            settings.preloadAudioData = true;
            importer.defaultSampleSettings = settings;
            importer.SaveAndReimport();
        }
    }

    static CombatVoiceBank CreateOrFillBank()
    {
        var bank = AssetDatabase.LoadAssetAtPath<CombatVoiceBank>(BankPath);
        if (bank == null)
        {
            bank = ScriptableObject.CreateInstance<CombatVoiceBank>();
            AssetDatabase.CreateAsset(bank, BankPath);
        }

        var so = new SerializedObject(bank);
        foreach (var (field, folder) in Groups)
        {
            var clips = so.FindProperty(field).FindPropertyRelative("clips");
            if (clips.arraySize > 0) continue;
            var paths = ClipPaths($"{VoiceDir}/{folder}");
            clips.arraySize = paths.Length;
            for (int i = 0; i < paths.Length; i++)
                clips.GetArrayElementAtIndex(i).objectReferenceValue =
                    AssetDatabase.LoadAssetAtPath<AudioClip>(paths[i]);
            if (paths.Length == 0)
                Debug.LogWarning($"[CombatVoiceSetup] No clips in {VoiceDir}/{folder}.");
        }
        if (so.ApplyModifiedPropertiesWithoutUndo()) EditorUtility.SetDirty(bank);
        return bank;
    }
}
